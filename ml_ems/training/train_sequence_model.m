function artifact=train_sequence_model(cfg,data,method,member)
rng(cfg.seed+member-1,'twister'); outputs=4*cfg.control.horizon;
head=fullyConnectedLayer(outputs,'Name','prediction');
if isfield(data,'target_mode')&&strcmp(data.target_mode,'lastvalue_residual')
 head=fullyConnectedLayer(outputs,'Name','prediction','WeightsInitializer','zeros','BiasInitializer','zeros');
end
if strcmp(method,'lstm')
 layers=[sequenceInputLayer(8,'Normalization','none');lstmLayer(64,'OutputMode','last'); ...
  fullyConnectedLayer(64);reluLayer;head;regressionLayer];
else
 layers=layerGraph([sequenceInputLayer(8,'Normalization','none','Name','input');fullyConnectedLayer(32,'Name','embed'); ...
  positionEmbeddingLayer(32,cfg.control.history,'Name','position');additionLayer(2,'Name','posadd'); ...
  selfAttentionLayer(4,32,'AttentionMask','causal','Name','attention');additionLayer(2,'Name','residual'); ...
  layerNormalizationLayer('Name','norm1');fullyConnectedLayer(64,'Name','ff1');reluLayer('Name','relu'); ...
  fullyConnectedLayer(32,'Name','ff2');additionLayer(2,'Name','ffadd');layerNormalizationLayer('Name','norm2'); ...
  indexing1dLayer('last','Name','last');head;regressionLayer('Name','loss')]);
 layers=connectLayers(layers,'embed','posadd/in2'); layers=connectLayers(layers,'posadd','residual/in2');
 layers=connectLayers(layers,'norm1','ffadd/in2');
end
options=trainingOptions('adam','MaxEpochs',cfg.epochs,'MiniBatchSize',cfg.batch_size,'InitialLearnRate',1e-3, ...
 'Shuffle','every-epoch','ValidationData',{data.validation.X,data.validation.Y},'ValidationFrequency',20, ...
 'ValidationPatience',8,'OutputNetwork','best-validation-loss','GradientThreshold',1, ...
 'Verbose',false,'Plots','none','ExecutionEnvironment','cpu');
[net,info]=trainNetwork(data.train.X,data.train.Y,layers,options);
artifact=struct('net',net,'info',info,'muX',data.muX,'sigmaX',data.sigmaX,'muY',data.muY,'sigmaY',data.sigmaY, ...
 'seed',cfg.seed+member-1,'dataset',data.dataset.folder,'method',method,'cfg',cfg.control);
if isfield(data,'target_mode'), artifact.target_mode=data.target_mode; end
save_artifact(artifact,cfg,method,member);
end
