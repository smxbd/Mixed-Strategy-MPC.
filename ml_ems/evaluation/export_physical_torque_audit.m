function tableOut=export_physical_torque_audit(run,p,filename)
a=physical_torque_audit(run,p);[~,o]=synchronized_physical_observations(run);
tableOut=table(a.time,a.engine_speed,o(:,17),a.engine_limit,a.engine_reserve, ...
 a.engine_excess,a.engine_violation,a.engine_speed_outside,a.engine_limit_unknown, ...
 a.A.speed,a.A.torque,a.A.lower,a.A.upper,a.A.peak_lower,a.A.peak_upper, ...
 a.A.nominal_excess,a.A.peak_excess,a.A.nominal_violation,a.A.peak_violation,a.A.overspeed, ...
 a.B.speed,a.B.torque,a.B.lower,a.B.upper,a.B.peak_lower,a.B.peak_upper, ...
 a.B.nominal_excess,a.B.peak_excess,a.B.nominal_violation,a.B.peak_violation,a.B.overspeed, ...
 'VariableNames',{'time_s','engine_rpm','engine_torque_Nm','engine_limit_Nm', ...
 'engine_reserve_Nm','engine_excess_Nm','engine_violation','engine_speed_outside','engine_speed_undefined', ...
 'motorA_rpm','motorA_torque_Nm','motorA_lower_Nm','motorA_upper_Nm','motorA_peak_lower_Nm','motorA_peak_upper_Nm', ...
 'motorA_nominal_excess_Nm','motorA_peak_excess_Nm','motorA_nominal_violation','motorA_peak_violation','motorA_overspeed', ...
 'motorB_rpm','motorB_torque_Nm','motorB_lower_Nm','motorB_upper_Nm','motorB_peak_lower_Nm','motorB_peak_upper_Nm', ...
 'motorB_nominal_excess_Nm','motorB_peak_excess_Nm','motorB_nominal_violation','motorB_peak_violation','motorB_overspeed'});
assert(height(tableOut)==numel(run.physical.time),'EMS:SampleLoss','Physical samples lost.');
writetable(tableOut,filename);
end
